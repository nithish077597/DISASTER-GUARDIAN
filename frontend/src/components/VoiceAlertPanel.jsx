import { useState } from 'react';
import { Volume2, Send, Radio, Sparkles, CheckCircle2 } from 'lucide-react';
import { useRealtime } from '../context/RealtimeContext';
import { voiceAssistantService } from '../services/voiceAssistantService';

const VOICE_TEXTS = {
  English: "Attention. Critical landslide risk detected in Kallar Valley. Please evacuate immediately using recommended safe routes.",
  Tamil: "???????????????! ????????????????????? ?????????????????????????????????????????? ???????????????????????? ?????????????????????????????? ?????????????????? ?????????????????????????????????????????????????????????. ???????????????????????? ????????????????????????????????? ????????????????????? ????????????????????????????????? ?????????????????????????????????.",
  Hindi: "??????????????? ?????????! ????????????????????? ???????????? ????????? ??????????????? ???????????????????????? ?????? ???????????? ????????? ????????? ??????????????? ??????????????? ???????????????????????? ??????????????? ?????? ??????????????? ???????????? ???????????? ?????????????????????",
};

export default function VoiceAlertPanel() {
  const { voiceLanguage, setVoiceLanguage, issueEmergencyAlert } = useRealtime();
  const [isSpeaking, setIsSpeaking] = useState(false);

  const handlePlayVoice = () => {
    setIsSpeaking(true);
    voiceAssistantService.speak(VOICE_TEXTS[voiceLanguage], voiceLanguage);
    setTimeout(() => setIsSpeaking(false), 5000);
  };

  return (
    <div className="p-6 bg-slate-900 border border-slate-800 rounded-2xl space-y-5 text-white select-none">
      <div className="flex items-center justify-between border-b border-slate-800 pb-3">
        <div className="flex items-center gap-2">
          <Volume2 className="w-5 h-5 text-cyan-400" />
          <h3 className="font-extrabold text-lg uppercase tracking-tight">AI VOICE ASSISTANT ENGINE</h3>
        </div>
        <span className="px-3 py-1 rounded-full bg-cyan-950 border border-cyan-500/40 text-cyan-300 font-extrabold text-xs font-mono uppercase tracking-wider flex items-center gap-1.5">
          <Sparkles className="w-3.5 h-3.5 text-cyan-400 animate-pulse" />
          <span>???? VOICE MODEL: ACTIVE</span>
        </span>
      </div>

      {/* Language Selector */}
      <div className="space-y-2">
        <label className="block text-xs font-bold text-slate-400 uppercase tracking-wider">Broadcast Speech Language</label>
        <div className="flex gap-2">
          {['English', 'Tamil', 'Hindi'].map((lang) => (
            <button
              key={lang}
              type="button"
              onClick={() => setVoiceLanguage(lang)}
              className={`flex-1 py-2.5 rounded-xl border text-xs font-bold transition-all ${
                voiceLanguage === lang
                  ? 'bg-cyan-600 border-cyan-500 text-white shadow-md'
                  : 'bg-slate-950 border-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              {lang === 'Tamil' ? '??????????????? (Tamil)' : lang}
            </button>
          ))}
        </div>
      </div>

      {/* Message Preview Box */}
      <div className="p-4 rounded-xl bg-slate-950 border border-slate-800 space-y-1">
        <span className="text-[11px] text-slate-500 font-mono block">AUDIO SPEECH SCRIPT ({voiceLanguage.toUpperCase()}):</span>
        <p className="text-xs text-white font-medium leading-relaxed font-sans">{VOICE_TEXTS[voiceLanguage]}</p>
      </div>

      {/* Action Buttons */}
      <div className="flex items-center gap-3">
        <button
          onClick={handlePlayVoice}
          className={`flex-1 py-3 rounded-xl font-extrabold text-xs uppercase tracking-wider border transition-all flex items-center justify-center gap-2 ${
            isSpeaking
              ? 'bg-cyan-600 text-white border-cyan-400 animate-pulse'
              : 'bg-slate-800 hover:bg-slate-700 text-cyan-300 border-slate-700'
          }`}
        >
          <Volume2 className={`w-4 h-4 text-cyan-400 ${isSpeaking ? 'animate-bounce' : ''}`} />
          <span>{isSpeaking ? '[ SPEAKING EMERGENCY WARNING... ]' : '[ ACTIVATE VOICE ASSISTANT ]'}</span>
        </button>

        <button
          onClick={() => {
            handlePlayVoice();
            issueEmergencyAlert();
          }}
          className="flex-1 py-3 rounded-xl bg-red-600 hover:bg-red-500 text-white font-extrabold text-xs uppercase tracking-wider shadow-lg shadow-red-600/30 transition-all flex items-center justify-center gap-2"
        >
          <Send className="w-4 h-4" />
          <span>[ SEND VOICE ALERT ]</span>
        </button>
      </div>
    </div>
  );
}
