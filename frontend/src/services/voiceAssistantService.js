import { alertSoundService } from './alertSoundService';

export const voiceAssistantService = {
  speak: (text, language = 'English') => {
    if (!('speechSynthesis' in window)) return;
    window.speechSynthesis.cancel();

    // PLAY 2-SECOND EMERGENCY ALARM SIREN TONE FIRST
    alertSoundService.playAlertSiren();

    const langCodes = {
      English: 'en-US',
      Tamil: 'ta-IN',
      Hindi: 'hi-IN',
    };

    const defaultTexts = {
      English: "Attention. Critical landslide risk detected in Kallar Valley. Please evacuate immediately using recommended safe routes.",
      Tamil: "???????????????! ????????????????????? ?????????????????????????????????????????? ???????????????????????? ?????????????????????????????? ?????????????????? ?????????????????????????????????????????????????????????. ???????????????????????? ????????????????????????????????? ????????????????????? ????????????????????????????????? ?????????????????????????????????.",
      Hindi: "??????????????? ?????????! ????????????????????? ???????????? ????????? ??????????????? ???????????????????????? ?????? ???????????? ????????? ????????? ??????????????? ??????????????? ???????????????????????? ??????????????? ?????? ??????????????? ???????????? ???????????? ?????????????????????",
    };

    const textToSpeak = text || defaultTexts[language] || defaultTexts.English;
    const utterance = new SpeechSynthesisUtterance(textToSpeak);
    utterance.lang = langCodes[language] || 'en-US';
    utterance.rate = 0.9;
    utterance.pitch = 1.0;

    // Delay speech 1.5 seconds so emergency alert sound effect plays first
    setTimeout(() => {
      window.speechSynthesis.speak(utterance);
    }, 1500);

    return utterance;
  },

  stop: () => {
    if ('speechSynthesis' in window) {
      window.speechSynthesis.cancel();
    }
  },

  askAssistant: (query, locationName = 'Coimbatore, Tamil Nadu', riskScore = 91, shelterName = 'Government Relief Centre', language = 'English') => {
    const qLower = query.toLowerCase();
    let responseText = '';

    if (qLower.includes('safe') || qLower.includes('safe here')) {
      if (riskScore >= 80) {
        responseText = `Your area near ${locationName} has critical landslide risk (${riskScore}/100). Please move to ${shelterName}, approximately 2.4 km away.`;
      } else {
        responseText = `Your current location at ${locationName} has low risk. All monitoring systems report safe conditions.`;
      }
    } else if (qLower.includes('flooding') || qLower.includes('flood')) {
      responseText = `Flooding hazard recorded near drainage paths. Please avoid low-lying roads and move toward higher ground at ${shelterName}.`;
    } else if (qLower.includes('landslide') || qLower.includes('crack')) {
      responseText = `Landslide hazard alert active. Avoid Village Road B and steep mountain slopes. Proceed via NH-707 highway detour.`;
    } else if (qLower.includes('do') || qLower.includes('what should i do')) {
      responseText = `Follow three steps: First, stay away from steep slopes. Second, take the safe route to ${shelterName}. Third, press Emergency SOS if you need immediate rescue.`;
    } else {
      responseText = `Emergency Assistant active for ${locationName}. Landslide risk score is ${riskScore}/100. Nearest safe shelter is ${shelterName}.`;
    }

    voiceAssistantService.speak(responseText, language);
    return responseText;
  },
};
